// 6. Generate Video from text using gemini-interactions-api with gemini-omni-1.1-flash
app.post('/api/gemini/generate-video', async (req, res) => {
  try {
    const { prompt, aspectRatio = '16:9' } = req.body;
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    const chosenAspect = aspectRatio === '9:16' ? '9:16' : '16:9';

    const interaction = await ai.interactions.create(
      {
        model: 'gemini-omni-1.1-flash',
        input: prompt,
        background: false,
        store: false,
        stream: false,
        response_format: {
          type: 'video',
          aspect_ratio: chosenAspect,
          duration: '5s',
          resolution: '720p',
        },
      },
      { timeout: 300000 }
    );

    const videoPart = interaction.output_video;
    if (videoPart && videoPart.data) {
      return res.json({
        videoUrl: `data:${videoPart.mime_type || 'video/mp4'};base64,${videoPart.data}`,
        aspectRatio: chosenAspect,
      });
    }

    return res.status(500).json({ error: 'Video generation completed but no video data returned' });
  } catch (error: any) {
    console.error('Video generation error:', error);
    return res.status(500).json({ error: error.message || 'Video generation failed' });
  }
});

