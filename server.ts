// 1. Text-to-Speech using gemini-3.8-flash-tts
app.post('/api/gemini/tts', async (req, res) => {
  try {
    const { text, speaker = 'Alex', style = 'Friendly, upbeat financial assistant' } = req.body;
    if (!text) {
      return res.status(400).json({ error: 'Text prompt is required' });
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: `${speaker}: ${text}`,
              speechMetadata: {
                speaker,
                style,
              },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName: 'Kore' },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    if (!base64Audio) {
      return res.status(500).json({ error: 'No audio generated by the model' });
    }

    return res.json({
      audio: `data:audio/wav;base64,${base64Audio}`,
      rawBase64: base64Audio,
    });
  } catch (error: any) {
    console.error('TTS error:', error);
    return res.status(500).json({ error: error.message || 'TTS generation failed' });
  }
});

// 2. Create & Edit Images using gemini-nano-banana-2.1
app.post('/api/gemini/create-edit-image', async (req, res) => {
  try {
    const { prompt, base64Image, mimeType = 'image/png' } = req.body;
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    const parts: any[] = [];
    if (base64Image) {
      parts.push({
        inlineData: {
          data: base64Image.replace(/^data:image\/[a-z]+;base64,/, ''),
          mimeType,
        },
      });
    }
    parts.push({ text: prompt });

    const response = await ai.models.generateContent({
      model: 'gemini-nano-banana-2.1',
      contents: { parts },
      config: {
        imageConfig: {
          aspectRatio: '1:1',
          imageSize: '1K',
        },
      },
    });

    let imageUrl = null;
    const partsArray = response.candidates?.[0]?.content?.parts || [];
    for (const part of partsArray) {
      if (part.inlineData?.data) {
        imageUrl = `data:${part.inlineData.mimeType || 'image/png'};base64,${part.inlineData.data}`;
        break;
      }
    }

    if (!imageUrl) {
      return res.status(500).json({ error: 'No image returned by gemini-nano-banana-2.1' });
    }

    return res.json({ imageUrl });
  } catch (error: any) {
    console.error('Create/edit image error:', error);
    return res.status(500).json({ error: error.message || 'Image generation failed' });
  }
});

